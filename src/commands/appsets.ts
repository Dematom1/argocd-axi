import { statSync } from "node:fs";
import { resolve } from "node:path";
import { argocdJson } from "../argocd.js";
import {
  CONTEXT_FLAG,
  getInt,
  parseArgs,
  validateName,
  type CommandSpec,
} from "../args.js";
import { validationError } from "../errors.js";
import {
  appName,
  appSources,
  destinationSummary,
  plural,
  truncate,
  type AppSource,
  type Application,
} from "../model.js";
import { Redactor } from "../redact.js";
import { encodeObject } from "../toon.js";
import {
  contextOption,
  contextSuffix,
  dispatch,
  finish,
  type Subcommand,
} from "./common.js";

interface ApplicationSet {
  metadata?: { name?: string; namespace?: string };
  spec?: {
    generators?: Array<Record<string, unknown>>;
    template?: {
      metadata?: { name?: string };
      spec?: {
        project?: string;
        source?: AppSource;
        sources?: AppSource[];
        destination?: { server?: string; name?: string; namespace?: string };
      };
    };
    syncPolicy?: {
      preserveResourcesOnDeletion?: boolean;
      applicationsSync?: string;
    };
  };
  status?: {
    conditions?: Array<{
      type?: string;
      status?: string;
      message?: string;
      reason?: string;
    }>;
    resources?: Array<{
      name?: string;
      namespace?: string;
      status?: string;
      health?: { status?: string };
    }>;
  };
}

const NOT_FOUND_HELP = ["Run `argocd-axi appsets` to list ApplicationSets"];

function generatorKinds(appset: ApplicationSet): string {
  const kinds = (appset.spec?.generators ?? []).flatMap((g) =>
    Object.keys(g).filter((k) => k !== "selector"),
  );
  return kinds.length > 0 ? kinds.join(", ") : "none";
}

function appsetStatus(appset: ApplicationSet): string {
  const conditions = appset.status?.conditions ?? [];
  const error = conditions.find(
    (c) => c.type === "ErrorOccurred" && c.status === "True",
  );
  if (error)
    return `error: ${truncate(error.message ?? error.reason ?? "unknown", 100)}`;
  const upToDate = conditions.find((c) => c.type === "ResourcesUpToDate");
  if (upToDate?.status === "True") return "up to date";
  if (upToDate)
    return truncate(
      upToDate.message ?? upToDate.reason ?? "not up to date",
      100,
    );
  return "unknown";
}

export const APPSETS_LIST_SPEC: CommandSpec = {
  path: "appsets",
  summary:
    "List ApplicationSets with their generators and status, errors first",
  positionals: [],
  flags: [
    {
      name: "--limit",
      kind: "value",
      valueName: "n",
      description: "Rows to show (default 100)",
    },
    CONTEXT_FLAG,
  ],
  examples: ["argocd-axi appsets"],
  notes: [
    "Apps generated by an ApplicationSet are overwritten from its template, so change the ApplicationSet rather than its apps",
  ],
};

export async function appsetsList(args: string[]): Promise<string> {
  const parsed = parseArgs(APPSETS_LIST_SPEC, args);
  const limit = getInt(parsed, "--limit", {
    default: 100,
    min: 1,
    max: 10_000,
  });
  const appsets =
    (await argocdJson<ApplicationSet[] | null>(
      "appset list",
      ["-o", "json"],
      contextOption(parsed),
    )) ?? [];
  if (appsets.length === 0) {
    return finish(
      [
        encodeObject({
          appsets: "0 ApplicationSets visible to this credential",
        }),
      ],
      undefined,
    );
  }
  const rows = appsets
    .map((a) => ({
      appset: a.metadata?.name ?? "",
      project: a.spec?.template?.spec?.project ?? "",
      generators: generatorKinds(a),
      status: appsetStatus(a),
    }))
    .sort(
      (a, b) =>
        Number(b.status.startsWith("error")) -
          Number(a.status.startsWith("error")) ||
        a.appset.localeCompare(b.appset),
    );
  const shown = rows.slice(0, limit);
  const scope = contextSuffix(parsed);
  const help = [
    `Run \`argocd-axi appsets view <name>${scope}\` for generators, template and generated apps`,
  ];
  if (shown.length < rows.length)
    help.unshift(
      `Run \`argocd-axi appsets --limit ${rows.length}${scope}\` to see all`,
    );
  return finish(
    [
      encodeObject({
        count: `${shown.length} of ${rows.length} total`,
        appsets: shown,
      }),
    ],
    undefined,
    help,
  );
}

export const APPSETS_VIEW_SPEC: CommandSpec = {
  path: "appsets view",
  summary:
    "One ApplicationSet: generators, template, sync policy, conditions and the apps it generated",
  positionals: [
    { name: "name", required: true, description: "ApplicationSet name" },
  ],
  flags: [CONTEXT_FLAG],
  examples: ["argocd-axi appsets view team-apps"],
};

function sourceRows(sources: AppSource[]) {
  return sources.map((s) => ({
    repo: s.repoURL ?? "",
    path: s.path ?? (s.chart ? `chart ${s.chart}` : ""),
    target: s.targetRevision ?? "HEAD",
  }));
}

export async function appsetsView(args: string[]): Promise<string> {
  const parsed = parseArgs(APPSETS_VIEW_SPEC, args);
  const name = validateName("appset", parsed.positionals[0] as string);
  const appset = await argocdJson<ApplicationSet>(
    "appset get",
    [name, "-o", "json"],
    {
      ...contextOption(parsed),
      failure: { notFoundHelp: NOT_FOUND_HELP },
    },
  );
  const template = appset.spec?.template?.spec;
  const redactor = new Redactor();
  const generated = appset.status?.resources ?? [];
  const problems = generated.filter(
    (r) =>
      r.status !== "Synced" ||
      (r.health?.status && r.health.status !== "Healthy"),
  );
  const summary = {
    name: appset.metadata?.name ?? name,
    status: appsetStatus(appset),
    generators: generatorKinds(appset),
    appName: appset.spec?.template?.metadata?.name,
    project: template?.project,
    destination: template?.destination
      ? destinationSummary({ spec: { destination: template.destination } })
      : undefined,
    applicationsSync:
      appset.spec?.syncPolicy?.applicationsSync ??
      "sync (create, update and delete)",
    preserveResourcesOnDeletion: appset.spec?.syncPolicy
      ?.preserveResourcesOnDeletion
      ? "yes"
      : "no",
    generatedApps: `${generated.length} total, ${problems.length} not synced or not healthy`,
  };
  const sources = sourceRows(
    template?.sources && template.sources.length > 0
      ? template.sources
      : template?.source
        ? [template.source]
        : [],
  );
  const conditions = (appset.status?.conditions ?? []).map((c) => ({
    type: c.type ?? "",
    status: c.status ?? "",
    message: truncate(redactor.text(c.message ?? ""), 200),
  }));
  const ordered = [
    ...problems,
    ...generated.filter((r) => !problems.includes(r)),
  ]
    .slice(0, 50)
    .map((r) => ({
      app: r.name ?? "",
      sync: r.status ?? "",
      health: r.health?.status ?? "",
    }));
  const help =
    ordered.length > 0
      ? [
          `Run \`argocd-axi apps view <app>${contextSuffix(parsed)}\` to diagnose a generated app`,
        ]
      : [];
  return finish(
    [
      encodeObject({ appset: redactor.deep(summary) }),
      sources.length > 0
        ? encodeObject({ templateSources: redactor.deep(sources) })
        : undefined,
      conditions.length > 0 ? encodeObject({ conditions }) : undefined,
      ordered.length > 0 ? encodeObject({ apps: ordered }) : undefined,
    ],
    redactor,
    help,
  );
}

export const APPSETS_GENERATE_SPEC: CommandSpec = {
  path: "appsets generate",
  summary:
    "Render the apps an ApplicationSet spec file would generate; creates nothing",
  positionals: [
    {
      name: "file",
      required: true,
      description: "Path to an ApplicationSet YAML or JSON file",
    },
  ],
  flags: [CONTEXT_FLAG],
  examples: ["argocd-axi appsets generate ./appset.yaml"],
  notes: [
    "The server renders the generators, so generators that list clusters or call SCM providers see real data",
  ],
};

export async function appsetsGenerate(args: string[]): Promise<string> {
  const parsed = parseArgs(APPSETS_GENERATE_SPEC, args);
  const file = parsed.positionals[0] as string;
  if (/^[a-z]+:\/\//i.test(file))
    throw validationError(
      "appsets generate takes a local file path, not a URL",
    );
  const path = resolve(file);
  let isFile: boolean;
  try {
    isFile = statSync(path).isFile();
  } catch {
    isFile = false;
  }
  if (!isFile) throw validationError(`file not found: ${file}`);

  const apps =
    (await argocdJson<Application[] | null>(
      "appset generate",
      [path, "-o", "json"],
      contextOption(parsed),
    )) ?? [];
  if (apps.length === 0) {
    return finish(
      [
        encodeObject({
          generated: `0 applications would be generated from ${file}`,
        }),
      ],
      undefined,
    );
  }
  const redactor = new Redactor();
  const rows = apps.map((app) => {
    const source = appSources(app)[0];
    return {
      app: appName(app),
      project: app.spec?.project ?? "",
      destination: destinationSummary(app),
      source: source
        ? `${source.repoURL ?? ""} ${source.path ?? source.chart ?? ""}`.trim()
        : "",
    };
  });
  return finish(
    [
      encodeObject({
        count: `${plural(rows.length, "application")} would be generated`,
        generated: redactor.deep(rows),
      }),
    ],
    redactor,
  );
}

const SUBCOMMANDS: Record<string, Subcommand> = {
  view: { spec: APPSETS_VIEW_SPEC, run: appsetsView },
  generate: { spec: APPSETS_GENERATE_SPEC, run: appsetsGenerate },
};

export const APPSETS_SPECS = [
  APPSETS_LIST_SPEC,
  APPSETS_VIEW_SPEC,
  APPSETS_GENERATE_SPEC,
];

export async function appsetsCommand(args: string[]): Promise<string> {
  return dispatch("appsets", args, SUBCOMMANDS, {
    spec: APPSETS_LIST_SPEC,
    run: appsetsList,
  });
}
